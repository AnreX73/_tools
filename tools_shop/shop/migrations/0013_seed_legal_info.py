def seed_legal(apps, schema_editor):
    Info = apps.get_model("shop", "Info")
    InfoSection = apps.get_model("shop", "InfoSection")

    for slug, kind, title, sections in PAGES:
        info, _ = Info.objects.get_or_create(
            slug=slug,
            defaults={
                "kind": kind,
                "title": title,
                "notice": NOTICE,
                "revision_date": date(2026, 10, 28),
                "is_active": True,
            },
        )
        for order, (heading, body) in enumerate(sections, start=1):
            InfoSection.objects.get_or_create(
                info=info,
                heading=heading,
                defaults={"body": body, "sort_order": order},
            )


